// Per-checkout dev-server ports. Single source of truth for the Vite config,
// scripts/dev.mjs, start.sh and the generated .claude/launch.json.
//
// Main checkout = slot 0 (5173 / 8000). Each linked git worktree gets a
// persistent slot N >= 1 (5173+N / 8000+N), recorded in <git common dir>/dev-ports.json.
// Deliberately independent of import.meta.url for path lookup: Vite inlines this
// file when it bundles the config.
import { execFileSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  realpathSync,
  renameSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const BASE_FRONTEND = 5173;
const BASE_BACKEND = 8000;
const MAX_SLOT = 99;

function git(cwd, args) {
  return execFileSync("git", args, {
    cwd,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"],
  }).trim();
}

function sleepSync(ms) {
  Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);
}

function withLock(commonDir, fn) {
  const lockDir = path.join(commonDir, "dev-ports.lock");
  const deadline = Date.now() + 5000;
  for (;;) {
    try {
      mkdirSync(lockDir);
      break;
    } catch (err) {
      if (err.code !== "EEXIST") throw err;
      try {
        if (Date.now() - statSync(lockDir).mtimeMs > 10000) {
          rmSync(lockDir, { recursive: true, force: true });
          continue;
        }
      } catch {
        continue; // vanished between mkdir and stat; retry
      }
      if (Date.now() > deadline) {
        throw new Error(`Timed out waiting for ${lockDir}`);
      }
      sleepSync(50);
    }
  }
  try {
    return fn();
  } finally {
    rmSync(lockDir, { recursive: true, force: true });
  }
}

function readRegistry(file) {
  try {
    const data = JSON.parse(readFileSync(file, "utf8"));
    if (data && typeof data.slots === "object" && data.slots) {
      return { version: 1, slots: { ...data.slots } };
    }
  } catch {
    // missing or corrupt: start fresh
  }
  return { version: 1, slots: {} };
}

function slotFor(commonDir, root) {
  const file = path.join(commonDir, "dev-ports.json");
  return withLock(commonDir, () => {
    const reg = readRegistry(file);
    const existing = reg.slots[root];
    if (Number.isInteger(existing) && existing >= 1) return existing;
    for (const p of Object.keys(reg.slots)) {
      if (!existsSync(p)) delete reg.slots[p];
    }
    const used = new Set(Object.values(reg.slots));
    let slot = 1;
    while (used.has(slot) && slot <= MAX_SLOT) slot++;
    if (slot > MAX_SLOT) {
      throw new Error(
        `No free dev-port slots (1..${MAX_SLOT}) in ${file}; remove stale entries.`,
      );
    }
    reg.slots[root] = slot;
    const tmp = `${file}.${process.pid}.tmp`;
    writeFileSync(tmp, `${JSON.stringify(reg, null, 2)}\n`);
    renameSync(tmp, file);
    return slot;
  });
}

export function getDevPorts({ cwd } = {}) {
  const dir = cwd ?? process.cwd();
  let root;
  let mainRoot;
  let commonDir = null;
  try {
    root = realpathSync(git(dir, ["rev-parse", "--show-toplevel"]));
    commonDir = realpathSync(
      git(dir, ["rev-parse", "--path-format=absolute", "--git-common-dir"]),
    );
    mainRoot = path.dirname(commonDir);
  } catch {
    root = realpathSync(dir);
    mainRoot = root;
    commonDir = null;
  }
  const isWorktree = commonDir !== null && root !== mainRoot;
  const slot = isWorktree ? slotFor(commonDir, root) : 0;
  const frontendPort = BASE_FRONTEND + slot;
  const backendPort = BASE_BACKEND + slot;
  return {
    root,
    mainRoot,
    isWorktree,
    slot,
    frontendPort,
    backendPort,
    frontendUrl: `http://localhost:${frontendPort}`,
    backendOrigin: `http://127.0.0.1:${backendPort}`,
  };
}

export function writeLaunchJson(ports) {
  const file = path.join(ports.root, ".claude", "launch.json");
  const config = {
    version: "0.0.1",
    configurations: [
      {
        name: "frontend",
        runtimeExecutable: "node",
        runtimeArgs: ["scripts/dev.mjs", "frontend"],
        port: ports.frontendPort,
        autoPort: false,
      },
      {
        name: "backend",
        runtimeExecutable: "node",
        runtimeArgs: ["scripts/dev.mjs", "backend"],
        port: ports.backendPort,
        autoPort: false,
      },
    ],
  };
  const content =
    "// Generated by scripts/dev-ports.mjs for this checkout. Don't edit: ports differ per worktree.\n" +
    `${JSON.stringify(config, null, 2)}\n`;
  let current = null;
  try {
    current = readFileSync(file, "utf8");
  } catch {
    // not there yet
  }
  if (current !== content) {
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, content);
  }
  return file;
}

function shq(s) {
  return `'${String(s).replace(/'/g, `'\\''`)}'`;
}

function isMain() {
  if (!process.argv[1]) return false;
  try {
    return realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (isMain()) {
  const ports = getDevPorts({ cwd: process.cwd() });
  const flag = process.argv[2];
  if (flag === "--json") {
    console.log(JSON.stringify(ports, null, 2));
  } else if (flag === "--shell") {
    console.log(`FRONTEND_PORT=${ports.frontendPort}`);
    console.log(`BACKEND_PORT=${ports.backendPort}`);
    console.log(`IS_WORKTREE=${ports.isWorktree ? 1 : 0}`);
    console.log(`MAIN_ROOT=${shq(ports.mainRoot)}`);
    console.log(`ROOT=${shq(ports.root)}`);
  } else if (flag === "--launch") {
    writeLaunchJson(ports);
    console.log(
      `Dev servers for this checkout: frontend ${ports.frontendUrl}, backend ${ports.backendOrigin}. ` +
        `Start them with preview_start "frontend" / "backend" (.claude/launch.json is generated per checkout by scripts/dev-ports.mjs).`,
    );
  } else {
    console.log(
      `frontend ${ports.frontendUrl}  backend ${ports.backendOrigin}  ` +
        (ports.isWorktree ? `(worktree slot ${ports.slot})` : "(main checkout)"),
    );
  }
}
