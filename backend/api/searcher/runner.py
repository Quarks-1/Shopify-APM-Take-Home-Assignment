def var_dir():
    return Path(settings.SEARCHER_VAR_DIR)


def _searches_dir():
    path = var_dir() / 'searches'
    path.mkdir(parents=True, exist_ok=True)
    return path


def log_path(run_id):
    return _searches_dir() / f'{run_id}.log'


def agent_output_path(run_id):
    return _searches_dir() / f'{run_id}.agent.json'


def default_agent_cwd():
    return Path(tempfile.gettempdir()) / 'shopify-searcher' / 'agent-cwd'


def repo_roots():
    """BASE_DIR and its ancestors that hold a .git (dir, or file in a worktree)."""
    base = BACKEND_DIR.resolve()
    return [d for d in (base, *base.parents) if (d / '.git').exists()]


def inside_repo(path):
    path = Path(path).resolve()
    return any(path == root or root in path.parents for root in repo_roots())


def agent_cwd(run_id=None):
    """The agent's empty working dir. Never inside the git repo: the repo's
    .claude/settings*.json (permission allow rules included) would load."""
    path = Path(settings.SEARCHER_AGENT_CWD)
    if inside_repo(path):
        message = (f'SEARCHER_AGENT_CWD {path} is inside the git repo; '
                   f'using {default_agent_cwd()} instead')
        logger.warning(message)
        if run_id is not None:
            _log(run_id, message)
        path = default_agent_cwd()
        if inside_repo(path):
            raise RuntimeError(f'no agent working directory outside the repo (tried {path})')
    path.mkdir(parents=True, exist_ok=True)
    return path


def db_path():
    return str(connection.settings_dict['NAME'])


def _log(run_id, message):
    stamp = timezone.now().strftime('%Y-%m-%d %H:%M:%S')
    try:
        with open(log_path(run_id), 'a', encoding='utf-8') as fh:
            fh.write(f'[{stamp}] {message.rstrip()}\n')
    except OSError:
        pass


def ensure_wrapper():
    """Write <VAR_DIR>/bin/searcher (atomically) and return its directory."""
    bin_dir = var_dir() / 'bin'
    bin_dir.mkdir(parents=True, exist_ok=True)
    path = bin_dir / 'searcher'
    try:
        if path.read_text(encoding='utf-8') == WRAPPER_SCRIPT and os.access(path, os.X_OK):
            return bin_dir
    except OSError:
        pass
    fd, tmp = tempfile.mkstemp(prefix='.searcher-', dir=bin_dir)
    with os.fdopen(fd, 'w', encoding='utf-8') as fh:
        fh.write(WRAPPER_SCRIPT)
    os.chmod(tmp, 0o755)
    os.replace(tmp, path)
    return bin_dir


# -------------------------------------------------------------- processes

def _pid_alive(pid):
    if not pid:
        return False
    try:
        done, _ = os.waitpid(pid, os.WNOHANG)  # reaps it if it is our zombie child
        if done == pid:
            return False
    except ChildProcessError:
        pass
    except OSError:
        pass
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True
    except OSError:
        return False
    return True


_signal_group = claude_cli.signal_group


def _reap_children():
    for proc in list(_children):
        try:
            finished = proc.poll() is not None
        except Exception:
            finished = True
        if finished:
            _children.remove(proc)


# ------------------------------------------------------------ run status

def _fail(run_id, message):
    """Mark an active run failed. Returns True if it was still active."""
    changed = SearchRun.objects.filter(pk=run_id, status__in=ACTIVE).update(
        status=RunStatus.FAILED, error=message[:2000], step=None, finished_at=timezone.now(),
    )
    obj_id = SearchRun.objects.filter(pk=run_id).values_list('object_id', flat=True).first()
    if obj_id is not None:
        sync_object_search(obj_id)
    return bool(changed)


def finalize(run):
    """Settle a run's final status. Idempotent; never touches a canceled run's status."""
    run.refresh_from_db()
    now = timezone.now()
    if run.status == RunStatus.CANCELED:
        SearchRun.objects.filter(pk=run.pk, finished_at__isnull=True).update(finished_at=now)
        SearchRun.objects.filter(pk=run.pk).update(step=None)
    else:
        accepted = run.candidates.filter(verdict=Verdict.ACCEPTED).count()
        queries = run.queries.all()
        all_rounds_failed = queries.exists() and not queries.filter(error='').exists()
        if accepted:
            status = RunStatus.DONE
        elif run.status == RunStatus.FAILED:
            status = RunStatus.FAILED
        elif run.error and (run.round_count == 0 or all_rounds_failed):
            status = RunStatus.FAILED
        else:
            status = RunStatus.EMPTY
        SearchRun.objects.filter(pk=run.pk).exclude(status=RunStatus.CANCELED).update(
            status=status, step=None, finished_at=run.finished_at or now,
        )
    run.refresh_from_db()
    sync_object_search(run.object_id)
    return run


# ---------------------------------------------------------- start/dispatch

def like_source_for(candidate):
    """The reference-product record a like run starts from. Photos are added
    by the worker (`prepare_like_run`)."""
    return {
        'candidateId': candidate.pk,
        'productGid': candidate.product_gid,
        'variantGid': candidate.variant_gid,
        'title': candidate.title,
        'seller': candidate.seller_name,
        'description': candidate.description,
        'imageUrls': [candidate.image_url] if candidate.image_url else [],
        'images': [],
    }


def start_like_search(space_object, candidate):
    """Start a "more like this" run seeded by one of the object's candidates.
    Returns (run, created) like `start_search`."""
    return start_search(space_object, like_candidate=candidate)


def start_refine_search(space_object):
    """Start a "Refresh" run shaped by the object's thumbs votes. Returns
    (run, created) like `start_search`; refused before any finished search."""
    return start_search(space_object, refine=True)


def _create_refine_run(space_object):
    """A queued refine run: feedback snapshot, round budget, liked pins."""
    if not feedback.has_finished_run(space_object):
        raise NoFinishedSearch('search this object before refining it')
    fb = feedback.build_feedback(space_object)
    extra = 1 + len(query_builder.liked_gids(fb))  # pref + liked:N rounds
    max_rounds = min(LIKE_MAX_ROUNDS_CAP, settings.SEARCHER_MAX_ROUNDS + extra)
    run = engine.create_run(space_object, status=RunStatus.QUEUED, mode=SearchMode.REFINE,
                            feedback=fb, max_rounds=max_rounds)
    feedback.pin_liked(run, space_object)
    return run


def start_search(space_object, like_candidate=None, refine=False):
    """Returns (run, created). Reuses the object's queued/running run if any."""
    if space_object.source == ObjectSource.IMPORTED:
        raise SearchRefused('imported objects are already owned')
    with transaction.atomic():
        active = (
            SearchRun.objects.filter(object_id=space_object.pk, status__in=ACTIVE)
            .order_by('-created_at').first()
        )
        if active is not None:
            return active, False
        if refine:
            run = _create_refine_run(space_object)
        elif like_candidate is None:
            run = engine.create_run(space_object, status=RunStatus.QUEUED)
        else:
            run = engine.create_run(
                space_object, status=RunStatus.QUEUED, mode=SearchMode.LIKE,
                like_source=like_source_for(like_candidate),
            )
    dispatch()
    run.refresh_from_db()
    return run, True


def reap_stale():
    """Fail running runs whose worker is gone. Returns the reaped run ids."""
    reaped = []
    cutoff = timezone.now() - timedelta(seconds=STALE_NO_PID_SECONDS)
    # Manual runs (CLI `searcher start`) are driven by hand and have no worker.
    running = SearchRun.objects.filter(status=RunStatus.RUNNING).exclude(
        agent_mode=AgentMode.MANUAL).only(
        'pk', 'object_id', 'worker_pid', 'agent_pid', 'started_at', 'created_at',
    )
    for run in running:
        if run.worker_pid:
            if _pid_alive(run.worker_pid):
                continue
            reason = WORKER_DIED
        else:
            if (run.started_at or run.created_at) > cutoff:
                continue
            reason = f'{WORKER_DIED} (no worker pid after {STALE_NO_PID_SECONDS}s)'
        changed = SearchRun.objects.filter(
            pk=run.pk, status=RunStatus.RUNNING, worker_pid=run.worker_pid,
        ).update(status=RunStatus.FAILED, error=reason, step=None, finished_at=timezone.now())
        if changed:
            _signal_group(run.agent_pid, signal.SIGTERM)  # don't leave an orphaned agent
            sync_object_search(run.object_id)
            _log(run.pk, f'reaped: {reason}')
            reaped.append(run.pk)
    return reaped


def dispatch():
    """Reap stale runs, then promote the oldest queued runs while fewer than
    SEARCHER_MAX_CONCURRENT are running. Returns the promoted run ids."""
    _reap_children()
    reap_stale()
    limit = max(1, settings.SEARCHER_MAX_CONCURRENT)
    promoted = []
    while True:
        with transaction.atomic():
            if SearchRun.objects.filter(status=RunStatus.RUNNING).count() >= limit:
                break
            nxt = (
                SearchRun.objects.filter(status=RunStatus.QUEUED)
                .order_by('created_at', 'pk').only('pk', 'object_id').first()
            )
            if nxt is None:
                break
            changed = SearchRun.objects.filter(pk=nxt.pk, status=RunStatus.QUEUED).update(
                status=RunStatus.RUNNING, step=RunStep.PLANNING, started_at=timezone.now(),
                worker_pid=None,
            )
        if not changed:
            continue
        sync_object_search(nxt.object_id)
        _spawn_worker(nxt.pk)
        promoted.append(nxt.pk)
    return promoted


def _spawn_worker(run_id):
    env = dict(os.environ)
    env['DJANGO_DB_PATH'] = db_path()
    argv = [sys.executable, str(MANAGE_PY), 'run_search', str(run_id)]
    try:
        with open(log_path(run_id), 'ab') as log:
            proc = subprocess.Popen(
                argv, cwd=str(BACKEND_DIR), env=env, shell=False, start_new_session=True,
                stdin=subprocess.DEVNULL, stdout=log, stderr=log,
            )
    except OSError as exc:
        _fail(run_id, f'could not start worker: {exc}')
        return None
    _children.append(proc)
    SearchRun.objects.filter(pk=run_id).update(worker_pid=proc.pid)
    return proc


# ------------------------------------------------------------------ cancel

def cancel_run(run):
    """Cancel a queued/running run. Returns (run, changed); a finished run is a no-op."""
    changed = SearchRun.objects.filter(pk=run.pk, status__in=ACTIVE).update(
        status=RunStatus.CANCELED, step=None, finished_at=timezone.now(),
    )
    run.refresh_from_db()
    if not changed:
        return run, False
    _log(run.pk, 'canceled')
    for pid in (run.agent_pid, run.worker_pid):
        _signal_group(pid, signal.SIGTERM)
    sync_object_search(run.object_id)
    dispatch()
    run.refresh_from_db()
    return run, True


# ------------------------------------------------------------------ worker

LIKE_MAX_ROUNDS_CAP = 20


def like_dir(run_id):
    return _searches_dir() / str(run_id) / 'like'


def prepare_like_run(run):
    """Like runs, in the worker (step PLANNING): look up every photo of the
    reference product, cache them and size the round budget. Never raises for
    a missing photo: with none, the product-id round is still available."""
    run_id = run.pk
    source = dict(run.like_source or {})
    fallback = [u for u in source.get('imageUrls') or [] if isinstance(u, str)]
    urls = []
    try:
        envelope = ucp_client.get_product(source.get('productGid') or '')
        urls = like_images.image_urls((envelope.get('result') or {}).get('product'))
    except ucp_client.UcpError as exc:
        _log(run_id, f'like: get_product failed ({exc}); using the candidate image')
    log = lambda message: _log(run_id, message)  # noqa: E731
    images = like_images.cache_images(urls, like_dir(run_id), log) if urls else []
    if not images and urls != fallback and fallback:
        urls = fallback[:settings.SEARCHER_LIKE_MAX_IMAGES]
        images = like_images.cache_images(urls, like_dir(run_id), log)
    source['imageUrls'] = urls
    source['images'] = images
    max_rounds = max(settings.SEARCHER_MAX_ROUNDS,
                     min(LIKE_MAX_ROUNDS_CAP, 2 * len(images) + 2))
    SearchRun.objects.filter(pk=run_id).update(like_source=source, max_rounds=max_rounds)
    run.refresh_from_db()
    _log(run_id, f'like: {len(images)} photo(s) cached, {max_rounds} rounds allowed')


REFINE_MAX_PHOTOS = 3


def prepare_refine_run(run):
    """Refine runs, in the worker: cache the main photo of the first liked
    products for the agent. Failures just skip a photo."""
    run_id = run.pk
    fb = dict(run.feedback or {})
    urls = [i.get('imageUrl') for i in fb.get('liked') or [] if isinstance(i.get('imageUrl'), str)]
    log = lambda message: _log(run_id, message)  # noqa: E731
    images = like_images.cache_images(urls[:REFINE_MAX_PHOTOS], like_dir(run_id), log) if urls else []
    fb['images'] = images
    SearchRun.objects.filter(pk=run_id).update(feedback=fb)
    run.refresh_from_db()
    _log(run_id, f'refine: {len(images)} liked photo(s) cached, '
                 f'{len(fb.get("pinned") or [])} pinned')

def execute(run):
    """Worker body: run the agent (or the deterministic loop), then finalize.
    Never leaves the run running, and always dispatches queued runs after."""
    run_id = run.pk
    try:
        run.refresh_from_db()
        if run.status == RunStatus.QUEUED:  # invoked directly, not via dispatch
            SearchRun.objects.filter(pk=run_id, status=RunStatus.QUEUED).update(
                status=RunStatus.RUNNING)
            run.refresh_from_db()
        if run.status != RunStatus.RUNNING:
            _log(run_id, f'worker {os.getpid()}: run is {run.status}, nothing to do')
            return
        fields = {'started_at': timezone.now(), 'step': RunStep.PLANNING}
        if run.worker_pid is None:
            fields['worker_pid'] = os.getpid()
        SearchRun.objects.filter(pk=run_id, status=RunStatus.RUNNING).update(**fields)
        sync_object_search(run.object_id)
        run.refresh_from_db()
        if run.mode == SearchMode.LIKE:
            try:
                prepare_like_run(run)
            except Exception:  # photos are a bonus; the product-id round still works
                _log(run_id, 'like: preparing photos failed:\n' + traceback.format_exc())
                run.refresh_from_db()
        elif run.mode == SearchMode.REFINE:
            try:
                prepare_refine_run(run)
            except Exception:  # photos are optional
                _log(run_id, 'refine: preparing photos failed:\n' + traceback.format_exc())
                run.refresh_from_db()
        mode = settings.SEARCHER_AGENT
        _log(run_id, f'worker {os.getpid()} started (agent={mode}, db={db_path()})')
        if mode == AgentMode.DETERMINISTIC:
            SearchRun.objects.filter(pk=run_id).update(
                agent_mode=AgentMode.DETERMINISTIC, agent_model='')
            engine.run_deterministic(run)
        else:
            _run_agent(run)
        run = finalize(run)
        _log(run_id, f'finished: {run.status}, {engine.accepted_count(run)}'
                     f'/{run.target} accepted in {run.round_count} rounds')
    except BaseException as exc:
        _log(run_id, 'worker error:\n' + traceback.format_exc())
        try:
            _fail(run_id, f'{type(exc).__name__}: {exc}')
        except Exception:
            _log(run_id, 'could not mark run failed:\n' + traceback.format_exc())
        if not isinstance(exc, Exception):
            raise
    finally:
        try:
            dispatch()
        except Exception:
            _log(run_id, 'dispatch after run failed:\n' + traceback.format_exc())


def _run_agent(run):
    run_id = run.pk
    SearchRun.objects.filter(pk=run_id).update(
        agent_mode=AgentMode.CLAUDE, agent_model=settings.SEARCHER_MODEL)
    failure, result = _invoke_claude(run)
    if result is not None:
        SearchRun.objects.filter(pk=run_id).update(agent_result=result)
        save_preferences(run, result)
    run.refresh_from_db()
    if not failure:
        return
    _log(run_id, f'agent failed: {failure}')
    if run.status != RunStatus.RUNNING:  # canceled (or reaped) meanwhile
        return
    accepted = engine.accepted_count(run)
    if accepted >= run.target:
        return
    if settings.SEARCHER_FALLBACK == 'deterministic':
        _log(run_id, 'falling back to the deterministic loop')
        SearchRun.objects.filter(pk=run_id).update(
            fallback_reason=failure, agent_mode=AgentMode.DETERMINISTIC)
        engine.run_deterministic(run)
    else:
        SearchRun.objects.filter(pk=run_id).update(error=failure)


def save_preferences(run, result):
    """Refine runs: keep what the agent says it learned from the votes."""
    if run.mode != SearchMode.REFINE:
        return None
    prefs = prompts.parse_preferences((result or {}).get('structured_output'))
    SearchRun.objects.filter(pk=run.pk).update(preferences=prefs)
    run.preferences = prefs
    return prefs


IMAGE_MEDIA_TYPES = ('image/jpeg', 'image/png', 'image/gif', 'image/webp')


def _photo_items(run):
    """(cached photo records, cap) of a like run's reference or a refine run's
    liked products; nothing for other runs."""
    mode = getattr(run, 'mode', None)
    if mode == SearchMode.LIKE:
        return (run.like_source or {}).get('images') or [], settings.SEARCHER_LIKE_MAX_IMAGES
    if mode == SearchMode.REFINE:
        return (run.feedback or {}).get('images') or [], REFINE_MAX_PHOTOS
    return [], 0


def like_photo_entries(run):
    """The cached photos that can go to the agent (like and refine runs), in
    index order, each file must still exist inside the run's like dir, be a
    supported image type and at most like_images.MAX_BYTES. Others are skipped."""
    raw, cap = _photo_items(run)
    if not raw:
        return []
    folder = like_dir(run.pk).resolve()
    out = []
    items = [i for i in raw if isinstance(i, dict)]
    for item in sorted(items, key=lambda i: i.get('index') if isinstance(i.get('index'), int) else 0):
        media_type = item.get('contentType')
        try:
            path = Path(item.get('path') or '').resolve()
            if (media_type not in IMAGE_MEDIA_TYPES or folder not in path.parents
                    or not path.is_file() or path.stat().st_size > like_images.MAX_BYTES):
                continue
        except (OSError, ValueError):
            continue
        out.append({'index': item.get('index'), 'path': path, 'contentType': media_type})
    return out[:cap]


def vibe_photo_entries(run):
    """The space-inspiration pin photos that can go to the agent (search and
    refine runs): each file must lie inside the vibes dir, be a supported image
    type and at most like_images.MAX_BYTES. Others are skipped."""
    if getattr(run, 'mode', None) == SearchMode.LIKE:
        return []
    vibes = getattr(run, 'vibes', None)
    raw = (vibes.get('photos') if isinstance(vibes, dict) else None) or []
    if not isinstance(raw, list):
        return []
    try:
        root = vibe_paths.vibes_dir()
    except (OSError, ValueError):
        return []
    items = [i for i in raw if isinstance(i, dict)]
    out = []
    for item in sorted(items, key=lambda i: i.get('index') if isinstance(i.get('index'), int) else 0):
        media_type = item.get('contentType')
        try:
            path = Path(item.get('path') or '').resolve()
            if (media_type not in IMAGE_MEDIA_TYPES or root not in path.parents
                    or not path.is_file() or path.stat().st_size > like_images.MAX_BYTES):
                continue
        except (OSError, ValueError):
            continue
        out.append({'index': item.get('index'), 'path': path, 'contentType': media_type,
                    'kind': 'vibe'})
    cap = 5 if isinstance(vibes, dict) and vibes.get('explicitReferences') else settings.VIBES_MAX_PHOTOS
    return out[:cap]


def agent_photos(run):
    """Every photo for the agent's first message: the like/refine photos
    (kind 'primary') first, then the space-inspiration pins (kind 'vibe')."""
    primary = [dict(p, kind='primary') for p in like_photo_entries(run)]
    return primary + vibe_photo_entries(run)


def _split_photos(photos):
    """(primary, vibe) photos; an entry without `kind` is primary."""
    vibe = [p for p in photos if p.get('kind') == 'vibe']
    return [p for p in photos if p.get('kind') != 'vibe'], vibe


def _image_block(photo):
    data = Path(photo['path']).read_bytes()
    return {'type': 'image', 'source': {
        'type': 'base64', 'media_type': photo['contentType'],
        'data': base64.b64encode(data).decode('ascii')}}


def build_stdin_message(run, photos):
    """One stream-json user message (a single JSON line, bytes): the user
    prompt as a text block, then one base64 image block per primary photo, and
    after a "Space inspiration photos:" text block the inspiration pin photos."""
    primary, vibe = _split_photos(photos)
    content = [{'type': 'text', 'text': prompts.build_user_prompt(
        run, photos_attached=len(primary), vibe_photos=len(vibe))}]
    content += [_image_block(photo) for photo in primary]
    if vibe:
        content.append({'type': 'text', 'text': 'Space inspiration photos:'})
        content += [_image_block(photo) for photo in vibe]
    line = json.dumps({'type': 'user', 'message': {'role': 'user', 'content': content}})
    return (line + '\n').encode('utf-8')


def stdin_path(run_id):
    return _searches_dir() / f'{run_id}.stdin.jsonl'


def build_argv(run, photos=None):
    """The exact `claude -p` invocation.

    Text mode (search runs, and like runs without photos): the prompt must
    directly follow -p, before the variadic --tools/--allowedTools.
    Photo mode (like runs with at least one cached photo): the prompt and the
    photos arrive as one stream-json user message on stdin, so no positional
    prompt; stream-json output needs --verbose. Same tools either way."""
    if photos is None:
        photos = agent_photos(run)
    primary, vibe = _split_photos(photos)
    photo_mode = bool(photos)
    head = [settings.SEARCHER_CLAUDE_BIN, '-p']
    if photo_mode:
        head += ['--input-format', 'stream-json', '--output-format', 'stream-json', '--verbose']
    else:
        head += [prompts.build_user_prompt(run, photos_attached=0), '--output-format', 'json']
    return head + [
        '--model', settings.SEARCHER_MODEL,
        '--json-schema', prompts.output_schema_json(),
        '--system-prompt', prompts.system_prompt(
            run, photos_attached=len(primary), vibe_photos=len(vibe)),
        '--tools', 'Bash',
        '--allowedTools', *ALLOWED_TOOLS,
        '--permission-mode', 'dontAsk',
        '--strict-mcp-config',
        '--setting-sources', 'project,local',
        # No CLAUDE.md, auto-memory, hooks, plugins or skills (setting sources
        # alone still load ~/.claude/CLAUDE.md). Auth is unaffected.
        '--safe-mode',
        '--max-turns', str(settings.SEARCHER_MAX_TURNS),
        '--no-session-persistence',
    ]


def _forwarded_value(name):
    value = getattr(settings, name)
    if name == 'SEARCHER_UCP_BIN' and os.sep not in str(value):
        value = shutil.which(str(value)) or value  # the agent's PATH is minimal
    return str(value)


def agent_env(run, wrapper_dir):
    """Built from scratch (explicit allowlist): nothing CLAUDE*/ANTHROPIC* leaks in."""
    extra = {
        'PATH': f'{wrapper_dir}:{SYSTEM_PATH}',
        'SEARCH_RUN_ID': str(run.pk),
        'SEARCHER_PYTHON': sys.executable,
        'SEARCHER_MANAGE': str(MANAGE_PY),
        'DJANGO_DB_PATH': db_path(),
    }
    for name in FORWARDED_SETTINGS:
        extra[name] = _forwarded_value(name)
    return claude_cli.base_env(extra)


trim_agent_result = claude_cli.trim_result
_parse_output = claude_cli.parse_output
_terminate = claude_cli.terminate


def _invoke_claude(run):
    """Run the agent to completion. Returns (failure_reason_or_None, trimmed_result_or_None)."""
    run_id = run.pk
    try:
        return _invoke_claude_with(run, run_id)
    finally:
        try:
            stdin_path(run_id).unlink()
        except OSError:
            pass


def _invoke_claude_with(run, run_id):
    argv = build_argv(run)
    stream = '--input-format' in argv
    photos = agent_photos(run) if stream else []
    env = agent_env(run, ensure_wrapper())
    out_path = agent_output_path(run_id)
    if stream:
        try:
            message = build_stdin_message(run, photos)
            fd = os.open(stdin_path(run_id), os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
            with os.fdopen(fd, 'wb') as fh:
                fh.write(message)
        except OSError as exc:
            return f'could not prepare the agent input: {exc}', None
    how = f'stream-json stdin with {len(photos)} photo(s) attached' if stream else '-p <prompt>'
    _log(run_id, f'agent: {argv[0]} {how} --model {settings.SEARCHER_MODEL} '
                 f'--max-turns {settings.SEARCHER_MAX_TURNS} (timeout {settings.SEARCHER_RUN_TIMEOUT:g}s)')
    res = claude_cli.run(
        argv, cwd=agent_cwd(run_id), env=env, out_path=out_path, err_path=log_path(run_id),
        timeout=settings.SEARCHER_RUN_TIMEOUT, stdin_path=stdin_path(run_id) if stream else None,
        is_canceled=lambda: not SearchRun.objects.filter(pk=run_id, status=RunStatus.RUNNING).exists(),
        on_spawn=lambda pid: SearchRun.objects.filter(pk=run_id).update(agent_pid=pid),
    )
    if res.spawn_error is not None:
        return f'claude could not start: {res.spawn_error}', None
    SearchRun.objects.filter(pk=run_id).update(agent_pid=None)
    rc, data, timed_out, canceled = res.rc, res.data, res.timed_out, res.canceled
    result = trim_agent_result(data) if data is not None else None
    subtype = (data or {}).get('subtype')
    _log(run_id, f'agent exited rc={rc} subtype={subtype} turns={(data or {}).get("num_turns")}')

    if canceled:
        return 'run is no longer running', result
    if timed_out:
        return f'agent timed out after {settings.SEARCHER_RUN_TIMEOUT:g}s', result
    if rc != 0:
        return f'claude exited with code {rc}' + (f' ({subtype})' if subtype else ''), result
    if data is None:
        return 'claude returned invalid JSON', None
    if data.get('is_error'):
        return f'claude reported an error ({subtype or "unknown"})', result
    return None, result
