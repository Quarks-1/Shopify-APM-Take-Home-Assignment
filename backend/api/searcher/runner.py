"""Background search runs.

    start_search(obj) -> queued run -> dispatch() -> worker process
    (`manage.py run_search <id>`) -> execute(run) -> headless claude agent
    (or the deterministic loop) -> finalize(run) -> dispatch() again.

Concurrency: SQLite runs with transaction_mode=IMMEDIATE (see settings), so
every `transaction.atomic()` block below holds the database write lock from
its first statement. That serializes the check-then-act steps (one active
run per object, the SEARCHER_MAX_CONCURRENT cap) across the web process,
the workers and the agent's `searcher` subcommands. Status changes are
conditional UPDATEs, so a cancel is never overwritten by a late writer.

Processes: every worker and every agent is started with
start_new_session=True, so its pid is also its process-group id and
timeout/cancel signal the whole group. Subprocesses always get argv lists,
never a shell.
"""
